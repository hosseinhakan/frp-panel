package frpconf

import (
	"fmt"
	"sort"
	"strings"
)

// RenderServer renders a ServerConfig into canonical frps TOML.
//
// The layout intentionally mirrors the original script's output style
// (dotted keys, grouped sections, QUIC block commented out when unused), so
// long-time users see a familiar file. Rendering is deterministic: golden
// tests in this package lock the exact bytes.
func RenderServer(c *ServerConfig) string {
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f+"\n", a...) }

	w("# Generated by frp-suite (frp-manager CLI / frp-panel Web UI)")
	w("# Managed frps configuration — edit via frp-manager or the panel for best results.")
	w("bindAddr = %q", c.BindAddr)
	w("bindPort = %d", c.BindPort)
	if c.QUICBindPort > 0 {
		w("quicBindPort = %d", c.QUICBindPort)
	}
	if c.KCPBindPort > 0 {
		w("kcpBindPort = %d", c.KCPBindPort)
	}
	w("")

	quic := c.Transport.QUIC
	if quic.IsZero() {
		// Non-QUIC configs carry no quic block; show the defaults as hints.
		quic = DefaultQUIC()
	}
	if c.QUICBindPort > 0 {
		w("transport.quic.keepalivePeriod = %d", quic.KeepalivePeriod)
		w("transport.quic.maxIdleTimeout = %d", quic.MaxIdleTimeout)
		w("transport.quic.maxIncomingStreams = %d", quic.MaxIncomingStreams)
	} else {
		// Preserve the original script's habit of leaving the tuning hints
		// visible (commented) when QUIC is not enabled.
		w("# transport.quic.keepalivePeriod = %d", quic.KeepalivePeriod)
		w("# transport.quic.maxIdleTimeout = %d", quic.MaxIdleTimeout)
		w("# transport.quic.maxIncomingStreams = %d", quic.MaxIncomingStreams)
	}
	w("")
	w("transport.heartbeatTimeout = %d", c.Transport.HeartbeatTimeout)
	w("transport.maxPoolCount = %d", c.Transport.MaxPoolCount)
	w("transport.tcpMux = %t", c.Transport.TCPMux)
	w("transport.tcpMuxKeepaliveInterval = %d", c.Transport.TCPMuxKeepaliveInterval)
	w("transport.tcpKeepalive = %d", c.Transport.TCPKeepalive)
	w("")
	w("auth.method = %q", c.Auth.Method)
	w("auth.token = %q", c.Auth.Token)
	w("")
	if c.WebServer.Enabled() {
		w("webServer.addr = %q", c.WebServer.Addr)
		w("webServer.port = %d", c.WebServer.Port)
		w("webServer.user = %q", c.WebServer.User)
		w("webServer.password = %q", c.WebServer.Password)
	}
	return b.String()
}

// RenderClient renders a ClientConfig into canonical frpc TOML.
//
// The suite follows the proven mikeesierrah profile: compact
// parseNumberRangePair templates for ports, no TLS/encryption/compression by
// default, and the long-haul keepalive/heartbeat values from Section 1.
// Configs that were created as plain [[proxies]] blocks stay plain: the
// RangeTemplate flag records which layout the file uses.
func RenderClient(c *ClientConfig) string {
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f+"\n", a...) }

	w("# Generated by frp-suite (frp-manager CLI / frp-panel Web UI)")
	w("# Managed frpc configuration — edit via frp-manager or the panel for best results.")
	w("serverAddr = %q", c.ServerAddr)
	w("serverPort = %d", c.ServerPort)
	w("")
	w("loginFailExit = %t", c.LoginFailExit)
	w("")
	w("auth.method = %q", c.Auth.Method)
	w("auth.token = %q", c.Auth.Token)
	w("")
	t := c.Transport
	w("transport.protocol = %q", t.Protocol)
	w("transport.tcpMux = %t", t.TCPMux)
	w("transport.tcpMuxKeepaliveInterval = %d", t.TCPMuxKeepaliveInterval)
	w("transport.dialServerTimeout = %d", t.DialServerTimeout)
	w("transport.dialServerKeepalive = %d", t.DialServerKeepalive)
	w("transport.poolCount = %d", t.PoolCount)
	w("transport.heartbeatInterval = %d", t.HeartbeatInterval)
	w("transport.heartbeatTimeout = %d", t.HeartbeatTimeout)
	w("transport.tls.enable = %t", t.TLS.Enable)
	w("transport.quic.keepalivePeriod = %d", t.QUIC.KeepalivePeriod)
	w("transport.quic.maxIdleTimeout = %d", t.QUIC.MaxIdleTimeout)
	w("transport.quic.maxIncomingStreams = %d", t.QUIC.MaxIncomingStreams)
	w("")
	if c.WebServer.Enabled() {
		w("webServer.addr = %q", c.WebServer.Addr)
		w("webServer.port = %d", c.WebServer.Port)
		w("webServer.user = %q", c.WebServer.User)
		w("webServer.password = %q", c.WebServer.Password)
		w("")
	}
	renderClientProxies(&b, c)
	return b.String()
}

// renderClientProxies appends either the compact range template or the
// expanded [[proxies]] blocks. The template is used only when every proxy
// forwards localPort == remotePort (the shape parseNumberRangePair can express).
func renderClientProxies(b *strings.Builder, c *ClientConfig) {
	if c.RangeTemplate && canRangeTemplate(c.Proxies) {
		local := strings.TrimSpace(c.RangeLocal)
		remote := strings.TrimSpace(c.RangeRemote)
		types := proxyTypes(c.Proxies)
		if len(types) == 0 {
			return
		}
		if local == "" {
			local = formatProxyPorts(c.Proxies, types[0])
		}
		if remote == "" {
			remote = local
		}
		first := c.Proxies[0]
		for i, typ := range types {
			if i > 0 {
				b.WriteString("\n")
			}
			fmt.Fprintf(b, "{{- range $_, $v := parseNumberRangePair %q %q }}\n", local, remote)
			b.WriteString("[[proxies]]\n")
			fmt.Fprintf(b, "name = %q\n", typ+"-{{ $v.First }}")
			fmt.Fprintf(b, "type = %q\n", typ)
			fmt.Fprintf(b, "localIP = %q\n", first.LocalIP)
			b.WriteString("localPort = {{ $v.First }}\n")
			b.WriteString("remotePort = {{ $v.Second }}\n")
			fmt.Fprintf(b, "transport.useEncryption = %t\n", first.Transport.UseEncryption)
			fmt.Fprintf(b, "transport.useCompression = %t\n", first.Transport.UseCompression)
			b.WriteString("{{- end }}\n")
		}
		return
	}
	for _, p := range c.Proxies {
		fmt.Fprintf(b, "[[proxies]]\n")
		fmt.Fprintf(b, "name = %q\n", p.Name)
		fmt.Fprintf(b, "type = %q\n", p.Type)
		fmt.Fprintf(b, "localIP = %q\n", p.LocalIP)
		fmt.Fprintf(b, "localPort = %d\n", p.LocalPort)
		fmt.Fprintf(b, "remotePort = %d\n", p.RemotePort)
		fmt.Fprintf(b, "transport.useEncryption = %t\n", p.Transport.UseEncryption)
		fmt.Fprintf(b, "transport.useCompression = %t\n", p.Transport.UseCompression)
		b.WriteString("\n")
	}
}

func canRangeTemplate(proxies []Proxy) bool {
	if len(proxies) == 0 {
		return false
	}
	first := proxies[0]
	for _, p := range proxies {
		if p.LocalPort != p.RemotePort || p.LocalIP != first.LocalIP ||
			p.Transport.UseEncryption != first.Transport.UseEncryption ||
			p.Transport.UseCompression != first.Transport.UseCompression {
			return false
		}
	}
	return true
}

// proxyTypes returns the distinct proxy types in stable order (tcp, udp).
func proxyTypes(proxies []Proxy) []string {
	has := map[string]bool{}
	for _, p := range proxies {
		has[p.Type] = true
	}
	out := []string{}
	for _, typ := range []string{"tcp", "udp"} {
		if has[typ] {
			out = append(out, typ)
		}
	}
	return out
}

func formatProxyPorts(proxies []Proxy, typ string) string {
	seen := map[int]bool{}
	var ports []int
	for _, p := range proxies {
		if p.Type != typ || seen[p.LocalPort] {
			continue
		}
		seen[p.LocalPort] = true
		ports = append(ports, p.LocalPort)
	}
	sort.Ints(ports)
	specs := make([]PortSpec, 0, len(ports))
	for _, p := range ports {
		specs = append(specs, PortSpec{Start: p, End: p})
	}
	return FormatPortSpecs(specs)
}

// WriteServer renders and writes a ServerConfig to disk.
func WriteServer(path string, c *ServerConfig) error {
	return writeFile(path, RenderServer(c))
}

// WriteClient renders and writes a ClientConfig to disk.
func WriteClient(path string, c *ClientConfig) error {
	return writeFile(path, RenderClient(c))
}
